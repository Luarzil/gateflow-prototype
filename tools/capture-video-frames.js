// Shared, asserted capture sequence for the current vehicle-first workflow.
module.exports = async function capture({ cdp, appUrl, evaluate, setViewport, waitForReady, screenshot, customer }) {
  const run = expression => evaluate(cdp, expression);
  const check = async (expression, label) => {
    if (!await run(expression)) throw new Error(`Capture assertion: ${label}`);
  };
  const click = selector => run(`(() => { const n = document.querySelector(${JSON.stringify(selector)}); if (!n || !n.getClientRects().length) throw Error('Not visible: ' + ${JSON.stringify(selector)}); n.click(); })()`);
  const input = (selector, value) => run(`(() => { const n = document.querySelector(${JSON.stringify(selector)}); if (!n.getClientRects().length) throw Error('Hidden input'); n.value = ${JSON.stringify(value)}; n.dispatchEvent(new Event('input', {bubbles:true})); })()`);
  const shot = async (name, expression) => { if (expression) await check(expression, name); await screenshot(cdp, name); };
  const visible = id => `document.querySelector('${id}').getClientRects().length > 0`;
  const nav = async shell => {
    await setViewport(cdp, shell === 'scanner' ? 390 : 1366, shell === 'scanner' ? 844 : 900, shell === 'scanner');
    await cdp.send('Page.navigate', {url: `${appUrl}?shell=${shell}`});
    await waitForReady(cdp);
    await check(`document.body.innerText.includes('Veri-Gate')`, shell);
  };
  const section = async name => { await click('[data-view="supervisorView"]'); await click(`[data-supervisor-section="${name}Section"]`); };
  const start = async barcode => { await click('#startScanButton'); await check(`document.querySelector('#barcodeInput').inputMode === 'none'`, 'scan-ready'); await input('#barcodeInput', barcode); };
  const driver = async (id = 'E1001') => { await click('#barcodeNext'); await input('#driverInput', id); await click('#driverNext'); };
  const submit = async direction => { await click(`#direction${direction}`); await click('#submitTransactionButton'); };
  await nav('scanner');
  await run('localStorage.clear()');
  await cdp.send('Page.reload', {ignoreCache:true});
  await waitForReady(cdp);
  await shot(customer ? '01-title.png' : '01-scanner-home.png', visible('#startScanButton'));
  if (customer) await shot('03-handheld.png');
  await start('G0001');
  await shot(customer ? '04-vehicle.png' : '02-vehicle-entry.png', visible('#barcodeNext'));
  await click('#barcodeNext');
  await check(`document.querySelector('#driverInput').inputMode === 'none'`, 'driver scan-ready');
  await input('#driverInput', 'E1001');
  await shot(customer ? '05-driver.png' : '03-driver-entry.png', visible('#driverNext'));
  await click('#driverNext');
  await shot(customer ? '06-movement.png' : '04-movement-choice.png', visible('#directionIn'));
  await click('#directionIn');
  await shot('review.png', visible('#submitTransactionButton'));
  await click('#submitTransactionButton');
  if (!customer) await shot('05-submitted-home.png', visible('#startScanButton'));
  await start('G9001');
  await click('#barcodeNext');
  await check(`ui.vehicleEntryMethod === 'scanner_field' && !document.body.innerText.includes('Check this barcode.')`, 'unknown scan has no warning');
  await shot(customer ? '07-unknown.png' : '03-unknown-vehicle.png', visible('#driverNext'));
  await input('#driverInput', 'E1001'); await click('#driverNext'); await submit('In');
  await check(`state.vehicles.some(v => v.assignedBarcode === 'G9001' && !v.barcodeNeedsReview)`, 'scanned unknown unflagged');
  await start('G9001'); await driver(); await click('#directionOut');
  await shot(customer ? '08-exit.png' : '06-unknown-out.png', `document.querySelector('#reviewStepTitle').innerText === 'Review Vehicle OUT'`);
  await click('#submitTransactionButton');
  await start('');
  await run(`document.querySelector('#barcodeInput').dispatchEvent(new PointerEvent('pointerdown', {bubbles:true}))`);
  await input('#barcodeInput', 'G00'); await click('#barcodeNext');
  await shot('typed-partial.png', `document.body.innerText.includes('Enter all 4 digits') && ui.step === 0 && ui.vehicleEntryMethod === 'manual'`);
  await input('#barcodeInput', 'G9002'); await click('#barcodeNext');
  await shot('typed-unknown.png', `document.body.innerText.includes('Check this barcode.') && ui.step === 1`);
  await input('#driverInput', 'E1001'); await click('#driverNext'); await submit('In');
  await check(`state.vehicles.some(v => v.assignedBarcode === 'G9002' && v.barcodeNeedsReview)`, 'typed unknown flagged');
  // Seed dates are relative to today; use a current, unauthorized driver for role refusal.
  await start('G0003'); await driver('E1003'); await submit('Out');
  await check(visible('#supervisorInput'), 'authorization override, not expired licence');
  await input('#supervisorInput', 'S3090'); await click('#approveSupervisorButton');
  await shot(customer ? '09-override.png' : '11-override-role.png', `document.querySelector('#supervisorStatus').innerText.includes('cannot approve')`);
  await run(`document.querySelector('#supervisorDuration').size = 5`);
  await shot('durations.png', `document.querySelector('#supervisorDuration').value === '9_hours' && document.querySelector('#supervisorDuration').options.length === 5`);
  await nav('console'); await section('vehicles');
  await shot(customer ? '10-console.png' : '07-console-shell.png', visible('#addVehicleButton'));
  await shot(customer ? '11-complete.png' : '08-gate-log.png', `document.body.innerText.includes('Check barcode')`);
  await run(`document.querySelector('#vehicleSearch').value = 'G9002'; document.querySelector('#vehicleSearch').dispatchEvent(new Event('input',{bubbles:true}))`);
  await shot('flagged-vehicle.png', `document.querySelector('#vehiclesTableBody').innerText.includes('Check barcode')`);
  await click('#vehiclesTableBody [data-vehicle-action="edit"]');
  await shot('vehicle-record.png', visible('#vehicleModal'));
  await click('#cancelVehicleButton');
  await click('#addVehicleButton'); await input('#vehicleVin', '1FTBW2CM5NKA12345');
  await shot('vin-only.png', `document.querySelector('#vehicleBarcode').value === ''`);
  await click('#vehicleForm button[type="submit"]');
  await check(`state.vehicles.some(v => v.vin === '1FTBW2CM5NKA12345' && v.assignedBarcode === 'G0006')`, 'VIN-only auto barcode');
  await input('#vehicleSearch', 'G0006');
  await shot('auto-barcode.png', `document.querySelector('#vehiclesTableBody').innerText.includes('G0006')`);
  await click('#vehiclesTableBody [data-vehicle-action="edit"]');
  if (!customer) await shot('09-complete-record.png', visible('#vehicleModal'));
  await click('#cancelVehicleButton'); await section('users');
  await shot('user-identifiers.png');
  await click('[data-user-action="edit"]');
  await shot(customer ? 'user-record.png' : '10-user-edit.png', visible('#desktopUserModal'));
  await click('#cancelDesktopUserButton'); await section('devices');
  await shot(customer ? '13-devices.png' : 'device-identifiers.png');
  await click('[data-device-action="edit"]');
  await shot('device-record.png', visible('#deviceModal'));
  await click('#cancelDeviceButton'); await section('drivers');
  await run(`document.querySelector('#authorizationDuration').size = 5`);
  await shot(customer ? '12-drivers.png' : 'authorization-options.png');
  await click('[data-view="searchView"]');
  await input('#filterDriver', 'E1001'); await click('#searchForm button[type="submit"]');
  await shot(customer ? '14-search.png' : '12-search.png', visible('#searchForm'));
  if (customer) await shot('02-problem.png');
  await check(`['1003','E1003','EMP-1003'].every(v => normalizeEmployee(v) === 'E1003') && normalizeEmployee('AB123') === 'AB123'`, 'employee normalization');
  await nav('scanner');
  // Add a clearly synthetic driver only in the disposable capture profile.
  await run(`state.drivers.push({...state.drivers[0], employeeNumber:'AB123', name:'Alex Demo'}); saveState()`);
  await start('G0001'); await click('#barcodeNext'); await input('#driverInput','AB123');
  await shot('alphanumeric-driver.png', `document.querySelector('#driverStatus').innerText.includes('Alex Demo')`);
  await click('#flowCancel');
  if (customer) { await shot('15-yard.png', visible('#startScanButton')); await shot('16-close.png'); }
};
